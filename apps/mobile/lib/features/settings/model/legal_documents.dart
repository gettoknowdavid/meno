/// The legal copy the app ships with.
///
/// This text belongs to the company, not to the code: it is reproduced here
/// section by section, exactly as supplied, so the About page and the register
/// form can show it without a network round trip. A store reviewer may open
/// it on a device without a connection.
///
/// It is bundled rather than fetched because a policy is part of the build it
/// applies to: a change to the terms should be a release, not a silent server
/// edit. When the website exists, these sections become the payload of its
/// policy pages (and the app can read them from there); the shape is
/// deliberately plain so that move is a copy, not a rewrite.
///
/// Only the signed-in copy is here: the app has no guest mode, so the separate
/// guest text the company supplied is not shipped.
library;

/// One titled block of a legal document.
final class LegalSection {
  /// Creates a titled block of legal copy.
  const new({required this.title, required this.body});

  /// The section heading.
  final String title;

  /// The section's prose, as written by the company.
  final String body;
}

/// A legal document the app has to be able to show.
final class LegalDocument {
  /// Creates a document from its ordered [sections].
  const new({required this.title, required this.sections});

  /// The document's name, used as the screen title.
  final String title;

  /// The document's sections, in the order they are read.
  final List<LegalSection> sections;
}

