//! The settings row and its theme enum.
//!
//! # What changed from `master`
//!
//! `strum` is gone: `Display` derived `AsRefStr`/`EnumString`/`strum::Display` for a
//! conversion nothing called anymore (`From<String>` below is the one a caller
//! reaches for, and it is deliberately lenient — an unknown stored value means the
//! column predates a new variant, and `system` is the safe answer). The wire
//! spelling comes from `serde`'s `rename_all = "lowercase"`, the database's from
//! `sqlx`'s — both shown here, so the three spellings are visible in one place.

use serde::{Deserialize, Serialize};
use uuid::Uuid;

/// One row of `settings`.
///
/// Has no timestamps: migration 0013 defines none, so there is nothing to format and
/// `wire_dates.rs` has nothing to catch here.
#[derive(Debug, Clone, sqlx::FromRow)]
pub struct Settings {
    /// Row id, generated by Postgres on insert.
    pub id: Uuid,
    /// The owner. `UNIQUE` — one settings row per user, which is what makes the
    /// upsert's `ON CONFLICT (user_id)` possible.
    pub user_id: Uuid,
    /// Push (FCM) notifications on/off.
    pub push_notifications: bool,
    /// In-app notifications on/off.
    pub app_notifications: bool,
    /// Email notifications on/off.
    pub email_notifications: bool,
    /// The raw device token for FCM. Never leaves the server — `SettingsResponse`
    /// reports only whether one is set.
    pub push_notification_token: Option<String>,
    /// Free-form client preferences, stored verbatim as JSONB.
    pub notification_preferences: serde_json::Value,
    /// UI theme.
    pub display: Display,
    /// Language tag, e.g. `en`.
    pub language: String,
}

impl Settings {
    /// The defaults for a user who has never saved any.
    ///
    /// # Why this exists, and why it must agree with the upsert
    ///
    /// Nothing inserts a settings row at signup, so `GET /settings` and the embedded
    /// block on `GET /users/me` answer from here for a fresh account — a missing row
    /// is a *default*, not a 404. The first `PATCH` then persists exactly these
    /// values for the fields the client did not send (`COALESCE($n, TRUE)` and friends
    /// in `repository::pg`), so what a client saw before its first save and what it
    /// sees after are identical. The migration's column defaults (`false`) only apply
    /// to rows inserted outside this path — there are none today.
    #[must_use]
    pub fn new(user_id: Uuid) -> Self {
        Self {
            id: Uuid::new_v4(),
            user_id,
            push_notifications: true,
            app_notifications: true,
            email_notifications: true,
            push_notification_token: None,
            notification_preferences: serde_json::json!({}),
            display: Display::System,
            language: "en".to_string(),
        }
    }
}

/// The UI theme. All three spellings are lowercase everywhere — wire, column, Rust.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Serialize, Deserialize, sqlx::Type)]
#[serde(rename_all = "lowercase")]
#[sqlx(type_name = "text", rename_all = "lowercase")]
pub enum Display {
    /// Follow the operating system.
    System,
    /// Always light.
    Light,
    /// Always dark.
    Dark,
}

impl Display {
    /// The exact string stored in the column and sent on the wire.
    #[must_use]
    pub const fn as_str(self) -> &'static str {
        match self {
            Self::System => "system",
            Self::Light => "light",
            Self::Dark => "dark",
        }
    }
}

impl std::fmt::Display for Display {
    /// The same lowercase spelling `serde` writes and `sqlx` stores — one spelling,
    /// three surfaces, visible together. (`master` got this from `strum::Display`;
    /// four lines of `match` replaces the dependency.)
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.write_str(self.as_str())
    }
}

impl From<String> for Display {
    /// Lenient on purpose: a stored value this build does not know means the column
    /// predates a new variant, and `system` is the answer that cannot be wrong —
    /// same rule `master` applied, kept because a hard error here would 500 a
    /// response whose only problem is that the server is older than the data.
    fn from(raw: String) -> Self {
        match raw.to_lowercase().as_str() {
            "dark" => Self::Dark,
            "light" => Self::Light,
            _ => Self::System,
        }
    }
}
